"""Summarize archived, completed independent oracles; never treat absent tests as passes."""
from pathlib import Path
import hashlib
import re
import sys

ROOT = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else Path(__file__).resolve().parent
inventory = {}
audits = []
dungeon_audits = []
sampling_scopes = {}
for path in sorted(ROOT.rglob("*.txt")):
    report_path = path.relative_to(ROOT).as_posix()
    text = path.read_text(encoding="utf-8-sig")
    for ident, family in re.findall(r"INVENTORY (\S+) type=(\S+)", text):
        inventory[ident] = family
    # Older reports predate STATUS; their terminal FAILURES block is authoritative.
    if "STATUS CHECKPOINT_INCOMPLETE" in text or not re.search(r"^FAILURES \d+$", text, re.M):
        continue
    created = re.search(r"^created=(.+)$", text, re.M).group(1)
    failure_section = text.split("\nFAILURES ", 1)[-1].split("\nUNVERIFIED ", 1)[0]
    fixtures = re.search(r"\bexplicitStarts=(\S+)", text)
    approach = re.search(r"\bfirstChunk=(\S+)", text)
    # Generating other families first can alter neighboring terrain/decorations.
    # A narrow regional retest must not erase a broader run's counterexample.
    sampling = {}
    for key in ("requestedDimensions", "includeTypes", "omitTypes", "locateRadiusChunks",
                "windowRadiusChunks", "queryAttempts", "predictedSamples", "dungeonRadiusChunks"):
        value = re.search(r"\b" + key + r"=(\S+)", text)
        sampling[key] = value[1] if value else "<not recorded>"
    sampling_description = " ".join(f"{key}={value}" for key, value in sampling.items())
    sampling_id = hashlib.sha256(sampling_description.encode()).hexdigest()[:10]
    sampling_scopes[sampling_id] = sampling_description
    for match in re.finditer(r"^PROGRESS seed=(-?\d+) type=DUNGEON actual=(\d+) predicted=(\d+)$", text, re.M):
        dungeon_seed = match[1]
        errors = sum('dungeon' in line.lower() and ('seed=' + dungeon_seed + ' ') in line
                     for line in failure_section.splitlines())
        matches = len(re.findall(r"^OBSERVATION dungeon container MATCH seed=" + re.escape(dungeon_seed) + r" ", text, re.M))
        dungeon_audits.append(dict(seed=dungeon_seed, actual=int(match[2]), predicted=int(match[3]),
                                  errors=errors, matches=matches, created=created, file=report_path,
                                  sampling=sampling_id,
                                  loot='skipLoot=true' not in text))
    seed = None
    loot = "skipLoot=true" not in text
    for line in text.splitlines():
        if line.startswith("SEED "):
            seed = line[5:]
        match = re.match(r"  (minecraft:\S+) actual=(\d+) (.+)", line)
        if not match or seed is None:
            continue
        ident = match[1]
        counts = dict((key, int(value)) for key, value in re.findall(r"(\w+)=(\d+)", line))
        # Failed comparisons are missing evidence, not observed item differences.
        counts['comparisonError'] = sum(
            'inventory-fill simulation failed' in failure
            and f'seed={seed} ' in failure and f'structure={ident} ' in failure
            for failure in failure_section.splitlines())
        # These fail before actual containers are scanned. Zero chest counters
        # therefore do not prove an empty structure or a successful comparison.
        counts['simulationError'] = sum(
            'loot simulator failed' in failure
            and f'seed={seed} ' in failure and f'id={ident} ' in failure
            for failure in failure_section.splitlines())
        fixture = next((entry for entry in fixtures[1].split(',') if entry.startswith(seed + ':')), None) if fixtures else None
        scope = ("fixture " + fixture.split(':', 1)[1]) if fixture else "regional search"
        if approach and approach[1] != '<default>':
            scope += "; first chunk " + approach[1]
        scope += "; sampling " + sampling_id
        if "history-retests" in path.relative_to(ROOT).parts:
            # These runs deliberately retain alternate histories. Never let a
            # passing replay replace an earlier same-scope counterexample.
            scope += "; retained history " + path.stem
        audits.append(dict(id=ident, seed=seed, counts=counts, loot=loot, scope=scope,
                           created=created, file=report_path))

# Keep the latest completed report per seed/structure/check class. Location-only
# reports must never replace earlier loot evidence or imply zero tested chests.
latest = {}
for row in sorted(audits, key=lambda item: item["created"]):
    latest[(row["id"], row["seed"], row["loot"], row["scope"])] = row

lines = ["# Minecraft 26.3 audit matrix", "",
         "Generated by `python docs/prediction-evidence/update_matrix.py` from completed reports in this directory.",
         "The inventory comes from the live 26.3 registry, with dungeon rooms tracked separately.",
         "Counts are bounded samples, not proof across all seeds. Older matching-loot reports did not",
         "separate unsupported metadata; only new `modeledLootMatch` counts certify the compared properties.", "",
         "Focused fixtures and different generation approaches are retained separately. Counts across these scopes may overlap.", "",
         "| Structure | Dimension | Location seeds | Loot seeds with containers | Archived loot evidence | Layout/rotation |",
         "|---|---|---|---|---|---|"]
for ident, family in sorted(inventory.items()):
    rows = [r for r in latest.values() if r["id"] == ident]
    location_seeds = sorted({r["seed"] for r in rows if r["counts"]["actual"] + r["counts"]["predicted"] > 0}, key=int)
    loot_rows = [r for r in rows if r["loot"]]
    loot_seeds = sorted({r["seed"] for r in loot_rows if r["counts"].get("actualChests", 0) > 0}, key=int)
    simulation_errors = sum(r['counts']['simulationError'] for r in loot_rows)
    dimension = "End" if family == "END_CITY" else "Nether" if family in {"BASTION", "FORTRESS", "NETHER_RUINED_PORTAL", "NETHER_FOSSIL"} else "Overworld"
    if family == "TRIAL_CHAMBER":
        status = "Deferred by request"
    elif family in {"MONUMENT", "NETHER_FOSSIL", "WITCH_HUT"}:
        status = "No loot containers"
    elif not loot_seeds:
        status = "NOT VERIFIED (no nonempty loot sample)"
    else:
        comparison_errors = sum(r['counts']['comparisonError'] for r in loot_rows)
        errors = sum(sum(r["counts"].get(k, 0) for k in ("missedChests", "extraChests", "lootMismatch")) for r in loot_rows) - comparison_errors
        metadata = sum(r['counts'].get('metadataUnverified', 0) for r in loot_rows)
        legacy = any('modeledLootMatch' not in r['counts']
                     for r in loot_rows if r['counts'].get('actualChests', 0))
        status = (f"{errors} recorded discrepancies" if errors else
                  f"{comparison_errors} comparisons unavailable" if comparison_errors else
                  f"Compared values matched; {metadata} inventories have unmodeled metadata" if metadata else
                  "Legacy comparisons; item-property coverage not recorded" if legacy else
                  "Bounded samples matched")
        if errors and comparison_errors:
            status += f"; {comparison_errors} comparisons unavailable"
    if simulation_errors:
        if status == "Bounded samples matched":
            status = "Compared samples matched; coverage incomplete"
        status += f"; {simulation_errors} loot simulations failed"
    layout_rows = [r for r in rows if 'layoutMatch' in r['counts']]
    layout = (f"{sum(r['counts']['layoutMatch'] for r in layout_rows)} matched / "
              f"{sum(r['counts'].get('layoutMismatch', 0) for r in layout_rows)} mismatched / "
              f"{sum(r['counts'].get('layoutUnverified', 0) for r in layout_rows)} unavailable") if layout_rows else "Not systematically audited"
    lines.append(f"| `{ident.removeprefix('minecraft:')}` | {dimension} | {', '.join(location_seeds) or 'UNTESTED'} | {', '.join(loot_seeds) or 'None'} | {status} | {layout} |")
dungeon_latest = {}
for row in sorted(dungeon_audits, key=lambda r: r['created']):
    if row['loot']: dungeon_latest[(row['seed'], row['sampling'])] = row
room_seeds = ', '.join(sorted({row['seed'] for row in dungeon_latest.values()}, key=int)) or 'UNTESTED'
room_errors = sum(row['errors'] for row in dungeon_latest.values())
room_matches = sum(row['matches'] for row in dungeon_latest.values())
room_status = f"{room_errors} recorded discrepancies" if room_errors else f"{room_matches} current stack comparisons matched; see reports"
lines += [f"| `monster_room` (configured feature) | Overworld | {room_seeds} | {room_seeds} | {room_status} | Configured feature |",
          "| `end_gateway` (configured feature) | End | Skipped by request | N/A | N/A | N/A |", "",
          "## Per-seed chest and loot results", "",
          "Each row is the latest archived loot run for that seed, registry ID and sampling scope. A focused or different-approach pass does not erase regional failures.",
          "Model matches include exact matches; exact is a product confidence flag, not a second test.", "",
          "Unavailable inventory-fill comparisons are retained separately; they prove neither a match nor a mismatch.", "",
          "Failed loot simulations occur before container scanning. Their zero counters do not establish empty structures; nonzero counters cover only the completed starts.", "",
          "| Structure | Seed | Scope | Actual / predicted starts | Missed / extra starts | Actual / predicted containers | Missed / extra containers | Loot mismatches | Comparison errors | Simulation errors | Model matches | Metadata unverified | Report |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
for row in sorted((r for r in latest.values() if r["loot"]), key=lambda r: (r["id"], int(r["seed"]))):
    c = row["counts"]
    pair = lambda a, b: f"{c.get(a, '?')} / {c.get(b, '?')}"
    mismatches = c['lootMismatch'] - c['comparisonError'] if 'lootMismatch' in c else '?'
    containers = pair('actualChests', 'predictedChests')
    if c['simulationError']:
        containers = (containers + ' (partial)' if c.get('actualChests', 0) or c.get('predictedChests', 0)
                      else 'Unavailable (simulation failed)')
    lines.append(f"| `{row['id'].removeprefix('minecraft:')}` | {row['seed']} | {row['scope']} | {pair('actual', 'predicted')} | {pair('missed', 'extra')} | {containers} | {pair('missedChests', 'extraChests')} | {mismatches} | {c['comparisonError']} | {c['simulationError']} | {c.get('modeledLootMatch', 'Not separately recorded')} | {c.get('metadataUnverified', 'Not separately recorded')} | [{row['file']}]({row['file']}) |")
lines += ["", "## Dungeon room evidence", "",
          "| Seed | Sampling | Actual / predicted rooms | Matched inventories | Discrepancies | Report |",
          "|---|---|---|---|---|---|"]
for row in sorted(dungeon_latest.values(), key=lambda r: int(r['seed'])):
    lines.append(f"| {row['seed']} | {row['sampling']} | {row['actual']} / {row['predicted']} | {row['matches']} | {row['errors']} | [{row['file']}]({row['file']}) |")
lines += ["", "## Sampling scopes", "",
          "Different family filters and search bounds retain separate evidence because they can change generation history.", "",
          "| Sampling | Recorded configuration |", "|---|---|"]
for sampling_id, description in sorted(sampling_scopes.items()):
    lines.append(f"| {sampling_id} | `{description}` |")
lines += ["", "Nonempty multi-seed samples do not establish universal accuracy. Recorded discrepancies and unmodeled properties are retained in [DISCREPANCY-CLASSIFICATION.md](DISCREPANCY-CLASSIFICATION.md); [README.md](README.md) records the evidence and current validation gates.", ""]
(ROOT / "AUDIT-MATRIX.md").write_text("\n".join(lines), encoding="utf-8")
print(f"Wrote matrix: {len(inventory)} registry IDs, {len(latest)} latest seed/check rows")
